/**
 * The drawings of the public demo showcase — what `npx tsx scripts/regenerate-demo-showcase.ts`
 * (`scripts/regenerate-demo-showcase.ts`) writes to
 * `lib/demo-showcase-planes.json`: every level of the demo's BPMN 2.0 file,
 * drawn by bpmn-js with the product's type and ink, as SVG.
 *
 * The record names the SHA-256 of the BPMN file it was drawn from;
 * `tests/demo-showcase-record.spec.ts` compares it with the file the engine of
 * the checkout writes, so the showcase can never show the map of an older
 * reading. No imports: read by the server page, the script and server-free specs.
 */

export const DEMO_SHOWCASE_PLANES_FILE = 'lib/demo-showcase-planes.json';

export const DEMO_SHOWCASE_PLANES_COMMENT =
  'Generated by `npx tsx scripts/regenerate-demo-showcase.ts` - do not edit. tests/demo-showcase-record.spec.ts fails when the engine writes a different BPMN file for the demo.';

/** The key of the top level; every other level is keyed by its sub-process element id. */
export const TOP_PLANE = 'process';

export interface ShowcasePlane {
  /** `process` for the top level, otherwise the id of the sub-process that opens it. */
  id: string;
  label: string;
  /** The drawing's size at 100 %, from its viewBox. */
  w: number;
  h: number;
  /** bpmn-js's own SVG export of the level, element ids kept (`data-element-id`). */
  svg: string;
}

export interface ShowcasePlanesRecord {
  $comment: string;
  /** SHA-256 of `buildDemoWorkspace().processMap.xml` at the time of drawing. */
  xmlSha256: string;
  renderer: string;
  planes: ShowcasePlane[];
}
