/** The service's entry: `main` when it names a source in the package, else `srv/service.ts`, else the first source. */
export function serviceEntry(reading: Pick<PackageReading, 'packageJson' | 'sources'>): string | null {
  const main = typeof reading.packageJson?.main === 'string' ? reading.packageJson.main : null;
  if (main && reading.sources.includes(main)) return main;
  if (reading.sources.includes('srv/service.ts')) return 'srv/service.ts';
  return reading.sources.find((p) => p.startsWith('srv/')) ?? reading.sources[0] ?? null;
}

/** A path as one shell word: as it is when it is plain, single-quoted otherwise. */
const shellArg = (p: string) => (/^[\w./-]+$/.test(p) ? p : `'${p.replace(/'/g, `'\\''`)}'`);

const npmName = (name: string) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'clean-core-package';

/**
 * The package.json of a generated (multi-file) Node package, normalised.
 *
 * The dependencies the model chose are kept. What is set here is what makes the
 * scripts, the container and the CI agree: `start` runs the entry through tsx,
 * `build` type-checks with the tsconfig that ships beside it, `test` runs the
 * suite with the runner it imports. Tools nothing calls any more (ts-node, and
 * Playwright when the suite is not a Playwright suite) are removed, and every
 * change is listed in `notes`.
 */
export function normalisedPackageJson(
  raw: string | undefined,
  opts: { name: string; entry: string | null; testFiles: readonly string[]; runner: TestRunner | null },
): { content: string; notes: string[] } {
  const notes: string[] = [];
  const parsed = parseJsonObject(raw);
  if (raw !== undefined && !parsed) notes.push('The generated package.json was not valid JSON; it was replaced by the template.');
  if (raw === undefined) notes.push('The generated package had no package.json; the template was used.');
  const pkg: PackageJsonShape = parsed ? { ...parsed } : { name: npmName(opts.name), version: '0.1.0', private: true };

  const dependencies: Record<string, string> = {};
  const devDependencies: Record<string, string> = {};
  for (const [k, v] of Object.entries(pkg.dependencies ?? {})) if (typeof v === 'string') dependencies[k] = v;
  for (const [k, v] of Object.entries(pkg.devDependencies ?? {})) if (typeof v === 'string') devDependencies[k] = v;

  const drop = (name: string, why: string) => {
    if (name in dependencies || name in devDependencies) {
      delete dependencies[name];
      delete devDependencies[name];
      notes.push(`Removed ${name}: ${why}.`);
    }
  };
  drop('ts-node', 'the service runs through tsx');
  if (opts.runner !== 'playwright') drop('@playwright/test', 'the suite is written for node:test, not Playwright');

  // tsx runs the service, so it is a runtime dependency; the compiler and the
  // Node types are build tools. Versions are pinned to the toolchain the
  // templates are written for.
  delete devDependencies.tsx;
  dependencies.tsx = TOOLCHAIN.tsx;
  delete dependencies.typescript;
  delete dependencies['@types/node'];
  devDependencies.typescript = TOOLCHAIN.typescript;
  devDependencies['@types/node'] = TOOLCHAIN['@types/node'];
  if (opts.runner === 'playwright') {
    delete dependencies['@playwright/test'];
    devDependencies['@playwright/test'] = devDependencies['@playwright/test'] ?? TOOLCHAIN['@playwright/test'];
  }

  const before = pkg.scripts && typeof pkg.scripts === 'object' ? Object.keys(pkg.scripts) : [];
  const scripts: Record<string, string> = {};
  if (opts.entry) {
    scripts.start = `node --import tsx ${opts.entry}`;
    scripts.dev = `tsx watch ${opts.entry}`;
  }
  scripts.build = 'tsc -p tsconfig.json';
  // Every suite file the package holds, not the first: with one named here and
  // two shipped, `npm test` ran one and CI passed while the other failed.
  if (opts.testFiles.length > 0 && opts.runner) {
    scripts.test = opts.runner === 'playwright' ? 'playwright test' : `tsx --test ${opts.testFiles.map(shellArg).join(' ')}`;
  }
  const dropped = before.filter((s) => !(s in scripts));
  if (before.length > 0) {
    notes.push(
      `Scripts set by the template (${Object.keys(scripts).join(', ')})${dropped.length ? `; dropped: ${dropped.join(', ')}` : ''}.`,
    );
  }

  const sorted = (o: Record<string, string>) => Object.fromEntries(Object.keys(o).sort().map((k) => [k, o[k]]));
  const out: PackageJsonShape = { ...pkg };
  if (opts.entry) out.main = opts.entry;
  else delete out.main;
  out.scripts = scripts;
  out.engines = { node: `>=${PACKAGE_NODE_MAJOR}` };
  out.dependencies = sorted(dependencies);
  out.devDependencies = sorted(devDependencies);
  return { content: `${JSON.stringify(out, null, 2)}\n`, notes };
}

/** The tsconfig of a generated Node package: type-check only — the service runs from TypeScript through tsx. */
export function packageTsconfig(sourcePaths: readonly string[]): string {
  const include = [
    ...new Set(sourcePaths.filter((p) => /\.tsx?$/.test(p)).map((p) => (p.includes('/') ? `${p.split('/')[0]}/**/*.ts` : p))),
  ].sort();
  return `${JSON.stringify(
    {
      compilerOptions: {
        target: 'ES2022',
        module: 'ESNext',
        moduleResolution: 'Bundler',
        strict: true,
        esModuleInterop: true,
        skipLibCheck: true,
        resolveJsonModule: true,
        experimentalDecorators: true,
        noEmit: true,
        types: ['node'],
      },
      include: include.length ? include : ['**/*.ts'],
    },
    null,
    2,
  )}\n`;
}

/**
 * The container of a generated Node package. The build stage installs
 * everything and type-checks; the runtime stage installs production
 * dependencies only and takes the **sources** from the build stage — never its
 * `node_modules`, which is what put the dev tools back into the runtime image.
 */
export function packageDockerfile(entry: string, runtimePaths: readonly string[]): string {
  const copies = runtimePaths.map((p) => `COPY --from=build /app/${p} ./${p}`).join('\n');
  return `# Container for review and local trials — a fixed template of Clean-Core.io.
# It has not been built, scanned or deployed by Clean-Core.io.
FROM node:${PACKAGE_NODE_MAJOR}-alpine AS build
WORKDIR /app
COPY package*.json ./
# No lockfile ships with the package; once yours is committed, npm ci is used.
RUN if [ -f package-lock.json ]; then npm ci; else npm install; fi
COPY . .
RUN npm run build

FROM node:${PACKAGE_NODE_MAJOR}-alpine AS runtime
WORKDIR /app
ENV NODE_ENV=production
ENV PORT=8080
COPY package*.json ./
RUN if [ -f package-lock.json ]; then npm ci --omit=dev; else npm install --omit=dev; fi && npm cache clean --force
COPY --from=build /app/tsconfig.json ./tsconfig.json
${copies}
USER node
EXPOSE 8080
CMD ["node", "--import", "tsx", "${entry}"]
`;
}

/** The CI workflow: Node 22, install with or without a lockfile, build, and the tests when there are any. */
