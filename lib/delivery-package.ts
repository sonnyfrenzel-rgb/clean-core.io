/**
 * The delivery package tells the truth (owner, 11.10.2026; external review of
 * the FI_Collection_Worklist bundle, findings F-04, F-05, F-08, F-09, F-10).
 *
 * The bundle used to carry a README written before its files were known: it
 * named `srv/service.cds` and `npm run dev` whether or not the package had
 * them, called the generated ABAP class a "released BAdI", and called a
 * Dockerfile that copied the builder's dev `node_modules` into the runtime a
 * "production container deployment setup". The reviewer found every one of
 * those, and a package.json whose `test` script ran Playwright over a suite
 * written for `node:test`.
 *
 * What this module does instead, deterministically and without a model:
 *
 *   - the build and test files of a Node package (package.json scripts,
 *     tsconfig.json, Dockerfile, CI) come from one set of templates that agree
 *     with each other and with the suite's own runner;
 *   - README.md is written from the entries actually in the archive — every
 *     file it names is there, every script it names is in package.json;
 *   - STATUS.md (the first file a reader opens) and manifest.json say what is
 *     implemented, a stub, proposed or missing, read off the files themselves —
 *     dependencies, the presence of a service model, the imports — and never
 *     claim more than that;
 *   - docs/decision.md carries the decision record and the Clean Core Score's
 *     deduction table, so "75/100" can be checked line by line;
 *   - docs/rule-register.md lists every business rule with its current
 *     meaning, proposal, decision, evidence and revision (CO review F16,
 *     12.10.2026).
 *
 * Pure: no React, no Firestore, no I/O. The page hands in what the project
 * holds (`DeliveryFacts`, built by `lib/delivery-facts.ts`) and writes what
 * comes back into the ZIP.
 */

