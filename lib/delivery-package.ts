export function knownLimits(reading: PackageReading, facts: DeliveryFacts, capabilities: readonly Capability[]): string[] {
  const out: string[] = ['Review version — not approved for production. No person has approved any part of it for production use.'];
  if (reading.kind === 'node') {
    out.push(implementationStatement(reading, facts));
    out.push(dataMode(reading).sentence);
  }
  if (reading.kind !== 'documents-only') {
    out.push('The code was generated by a language model from the analysis. Nothing here shows that it behaves as the ABAP program does — no old/new comparison is on record.');
  }
  if (facts.tests.status !== 'passed') out.push(`Tests: ${TEST_STATUS_WORDS[facts.tests.status].toLowerCase()} — ${facts.tests.sentence}`);
  else out.push('Tests passed against mocks in the test runner (Demonstrated · mock) — not against an SAP system.');
  for (const p of reading.publisher) out.push(`\`${p}\`: publisher sketch — not bound to a BAdI or standard event, not compiled in SAP.`);
  const unwired = capabilities.filter((c) => (c.status === 'missing' || c.status === 'proposed') && ['authentication', 'persistence', 'ui', 'service-model', 'cap-runtime'].includes(c.key));
  for (const c of unwired) out.push(`${c.label}: ${c.status} — ${c.evidence}`);
  if (reading.kind === 'node' && !reading.lockfile) out.push('No lockfile: dependency versions are not pinned.');
  if (reading.kind === 'node') out.push('Dockerfile and CI are fixed templates of Clean-Core.io; neither was built or run by Clean-Core.io.');
  if (facts.score.signed !== null) out.push('The Clean Core Score is a Clean-Core.io grade derived from the findings, not an SAP figure or a compliance percentage.');
  if (!facts.source.matchesSignedRun) out.push('The source on the project no longer matches the signed run, or there is no signed run: the identifiers below may not describe this package.');
  return out;
}

export function nextSteps(reading: PackageReading, facts: DeliveryFacts, capabilities: readonly Capability[]): string[] {
  const out: string[] = [];
  const t = facts.tests;
  if (t.status === 'failed' || t.status === 'incomplete') {
    out.push('Repair the test project and produce a run that gives a result (Testing tool) — the cause on record is under "Tests" above.');
  } else if (t.status === 'not-run') {
    out.push(t.scenarios > 0 ? 'Run the test suite (Testing tool) and keep its receipt with the package.' : 'Generate test scenarios and a suite (Testing tool), then run it.');
  } else if (t.status === 'stale') {
    out.push('Regenerate and run the tests: the ones on record were built for a previous source or code.');
  } else if (t.status === 'closed-not-verified') {
    out.push('Run the suite where it can run; until then testing stays closed, not verified.');
  }
  if (facts.rules.state === 'read' && facts.rules.counts.undecided + facts.rules.counts.clarify > 0) {
    out.push(`Decide the ${plural(facts.rules.counts.undecided + facts.rules.counts.clarify, 'open business rule')} — keep, change deliberately or drop — in the Business view; each is in \`${RULE_REGISTER_PATH}\`.`);
  } else if (facts.rules.state === 'not-read') {
    out.push('Check the business rules in the Business view — their state could not be read into this package.');
  }
  const d = facts.decision;
  if (d.state !== 'confirmed') {
    out.push(
      d.state === 'confirmed-earlier-run'
        ? 'Confirm the decision again on the current analysis run (Management).'
        : 'Decide the target with an owner in Management — Keep, Rebuild, Move to SAP standard or Retire — and confirm it.',
    );
  }
  const cap = capabilities.find((c) => c.key === 'cap-runtime');
  if (cap && cap.status !== 'implemented') {
    out.push('Either build the proposed CAP architecture (service model and @sap/cds runtime) or record that the delivered implementation is the target.');
  }
  if (reading.publisher.length) {
    out.push('Decide whether the process needs eventing at all; if it does, bind the publisher to a released event or BAdI and test it end to end in SAP.');
  }
  if (reading.kind === 'node' && dataMode(reading).mode === 'not-recorded') {
    out.push('Record where the data comes from (synthetic, an extract, a live system) with every run, and bind a live SAP source only after the steps above.');
  }
  if (reading.kind === 'node' && !reading.lockfile) out.push('Commit a package-lock.json, so CI and the container install pinned versions.');
  return out;
}

