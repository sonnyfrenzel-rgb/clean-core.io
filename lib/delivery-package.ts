const bytesOf = (text: string) => new TextEncoder().encode(text).length;

export const DELIVERY_MANIFEST_FORMAT = 'clean-core-delivery-manifest';
export const DELIVERY_MANIFEST_VERSION = 1;

/** The rule counts for the manifest; the rows themselves are in the register. */
function manifestRules(r: RuleFacts) {
  const files = { register: RULE_REGISTER_PATH, registerCsv: RULE_REGISTER_CSV_PATH };
  if (r.state !== 'read') return { ...r, ...files };
  return { state: r.state, basis: r.basis, total: r.rows.length, ...r.counts, states: ruleStateCounts(r.rows), ...files };
}

export function buildManifest(
  facts: DeliveryFacts,
  inputs: StatusInputs & { notes: Record<string, string[]> },
): string {
  const { reading, capabilities, files, notes } = inputs;
  const d = facts.decision;
  const manifest = {
    format: DELIVERY_MANIFEST_FORMAT,
    version: DELIVERY_MANIFEST_VERSION,
    approval: 'review-version-not-approved-for-production',
    generatedAt: facts.generatedAt,
    generatedBy: `Clean-Core.io ${facts.appVersion}`,
    project: { id: facts.projectId, name: facts.projectName, route: facts.route },
    source: {
      fileName: facts.source.fileName,
      sha256: facts.source.sha256,
      lines: facts.source.lines,
      matchesSignedRun: facts.source.matchesSignedRun,
    },
    run: {
      id: facts.run.id,
      engineVersion: facts.run.engineVersion,
      signed: facts.run.id !== null,
      verify: 'Download the audit pack from Delivery and check it at https://clean-core.io/verify-pack; this package is not signed.',
    },
    decision: {
      state: d.state,
      record: d.identity,
      option: d.option,
      programOption: d.optionKey ? DECISION_OPTION_LABELS[d.optionKey] : null,
      by: d.by,
      at: d.at,
      alternatives: DECISION_OPTIONS.map((o) => DECISION_OPTION_LABELS[o]),
      reasons: d.reasons,
      recommendation: d.recommendation,
      cost: d.cost,
      openConditions: d.conditions.filter((c) => c.status === 'open' || c.status === 'not determined').length,
    },
    // The rows are in docs/rule-register.md; the manifest carries the counts and points there.
    businessRules: manifestRules(facts.rules),
    tests: { status: facts.tests.status, scenarios: facts.tests.scenarios, sentence: facts.tests.sentence, detail: facts.tests.detail },
    score: {
      signed: facts.score.signed,
      rule: facts.score.rule,
      edition: facts.score.edition,
      derivation: facts.score.model ? 'docs/decision.md' : null,
    },
    dataMode: dataMode(reading).mode,
    implementation: implementationStatement(reading, facts),
    capabilities,
    statusLegend: PACKAGE_STATUS_LEGEND,
    files: files.map((f) => (notes[f.path] ? { ...f, changes: notes[f.path] } : f)),
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

