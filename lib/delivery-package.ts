const DOC_FILES: Readonly<Record<string, { what: string; origin: FileOrigin; status: PackageStatus }>> = Object.freeze({
  'docs/business-analysis.md': { what: 'Business analysis', origin: 'model-text', status: 'proposed' },
  'docs/solution-design.md': {
    what: 'Solution design — the target architecture as proposed, not what this package implements',
    origin: 'model-text',
    status: 'proposed',
  },
  'docs/business-documentation.md': { what: 'Business documentation (SOP)', origin: 'model-text', status: 'proposed' },
  'docs/developer-guidelines.md': { what: 'Developer guidelines for the route', origin: 'template', status: 'proposed' },
});

function originOf(e: BundleEntry, facts: DeliveryFacts): FileOrigin {
  if (e.origin) return e.origin;
  if (DOC_FILES[e.path]) return DOC_FILES[e.path].origin;
  if (/^docs\/process-[\w-]+\.md$/.test(e.path)) return facts.documentationFromEngine ? 'engine' : 'model-text';
  if (['.abapgit.xml', 'abaplint.json'].includes(e.path) || /\.clas\.xml$/.test(e.path)) return 'template';
  return 'generated';
}

/** Kind, status and a note for one file — from its path, its content and what the package reads as. */
export function classifyFile(e: BundleEntry, reading: PackageReading, facts: DeliveryFacts): { kind: FileKind; status: PackageStatus; note: string | null } {
  const p = e.path;
  if (p === 'STATUS.md') return { kind: 'status', status: 'implemented', note: null };
  if (p === 'README.md') return { kind: 'readme', status: 'implemented', note: null };
  if (p === 'manifest.json') return { kind: 'manifest', status: 'implemented', note: null };
  if (p === 'docs/decision.md') return { kind: 'decision-record', status: 'implemented', note: null };
  if (p === RULE_REGISTER_PATH) return { kind: 'rule-register', status: 'implemented', note: null };
  if (p === RULE_REGISTER_CSV_PATH) return { kind: 'rule-register-csv', status: 'implemented', note: null };
  if (DOC_FILES[p]) return { kind: 'documentation', status: DOC_FILES[p].status, note: 'Review material, not approved.' };
  if (/^docs\/process-[\w-]+\.md$/.test(p)) {
    return facts.documentationFromEngine
      ? { kind: 'documentation', status: 'implemented', note: 'Read by the engine from the signed source; business names and lanes are model proposals where marked.' }
      : { kind: 'documentation', status: 'proposed', note: 'Written by a language model — review material.' };
  }
  if (p.startsWith('docs/')) return { kind: 'documentation', status: 'proposed', note: 'Review material, not approved.' };
  if (p.startsWith('erp-triggers/') && /\.abap$/i.test(p)) {
    return { kind: 'erp-publisher', status: 'stub', note: 'Publisher sketch — not bound to a BAdI or standard event, not compiled in SAP.' };
  }
  if (p === 'package.json') return { kind: 'package-config', status: 'implemented', note: null };
  if (p === 'tsconfig.json') return { kind: 'typescript-config', status: 'implemented', note: null };
  if (p === 'Dockerfile') return { kind: 'container', status: 'implemented', note: 'Not built, scanned or deployed by Clean-Core.io.' };
  if (p.startsWith('.github/workflows/')) return { kind: 'ci', status: 'implemented', note: 'Not run by Clean-Core.io.' };
  if (p === '.abapgit.xml') return { kind: 'abapgit-config', status: 'implemented', note: null };
  if (p === 'abaplint.json' || /^playwright\.config\./.test(p)) return { kind: 'lint-config', status: 'implemented', note: null };
  if (/\.cds$/i.test(p)) {
    const service = reading.serviceCds.includes(p);
    return reading.capRuntime
      ? { kind: service ? 'cds-service' : 'cds-schema', status: 'implemented', note: null }
      : {
          kind: service ? 'cds-service' : 'cds-schema',
          status: 'proposed',
          note: 'CDS model only: package.json has no @sap/cds runtime, so nothing serves or persists it.',
        };
  }
  if (CODE_EXT.test(p)) {
    if (isTestPath(p)) {
      return {
        kind: 'test-suite',
        status: 'implemented',
        note: `Test suite (${reading.runner ?? 'node:test'}). Its run: ${TEST_STATUS_WORDS[facts.tests.status].toLowerCase()} — see STATUS.md.`,
      };
    }
    const stub = codeLines(e.content) < 5 || /throw\s+new\s+Error\(\s*['"`]not implemented/i.test(e.content);
    return {
      kind: reading.express.includes(p) || p === serviceEntry(reading) ? 'service-source' : 'source',
      status: stub ? 'stub' : 'implemented',
      note: stub ? 'Fewer than five lines of code, or it throws "not implemented".' : null,
    };
  }
  if (/\.clas\.abap$/i.test(p) && /test/i.test(p)) return { kind: 'test-suite', status: 'implemented', note: 'ABAP Unit class — runs only inside an SAP system.' };
  if (/\.(abap|asddls|asbdef|assrvd|assrvb)$/i.test(p)) return { kind: 'abap-object', status: 'implemented', note: 'Not imported into or activated in an SAP system.' };
  if (/\.xml$/i.test(p) && p.startsWith('src/')) {
    return { kind: 'abap-metadata', status: 'implemented', note: 'Generated, not produced by an abapGit serializer; names and attributes may need adjusting.' };
  }
  return { kind: 'other', status: 'implemented', note: null };
}

/** The capabilities the architecture and the build speak of, each with its state in the package. */
export function packageCapabilities(reading: PackageReading, facts: DeliveryFacts): Capability[] {
  if (reading.kind === 'abap') {
    return [
      {
        key: 'abap-objects',
        label: 'ABAP objects for an abapGit import',
        status: 'implemented',
        evidence: 'Sources and metadata under src/. Not imported into, activated in or run in an SAP system.',
      },
      {
        key: 'abap-unit',
        label: 'ABAP Unit tests',
        status: reading.kind === 'abap' && facts.tests.scenarios > 0 ? 'implemented' : 'missing',
        evidence: 'An ABAP Unit class runs only inside an SAP system; nothing here executes it.',
      },
    ];
  }
  if (reading.kind !== 'node') return [];
  const caps: Capability[] = [];
  const capProposed = capArchitectureProposed(reading, facts);
  const capRunning = reading.capRuntime && reading.capServed && reading.serviceCds.length > 0;
  if (capProposed || reading.capRuntime) {
    caps.push({
      key: 'cap-runtime',
      label: 'SAP CAP runtime',
      status: capRunning ? 'implemented' : 'proposed',
      evidence: capRunning
        ? `@sap/cds in package.json and a service model (${reading.serviceCds.join(', ')}).`
        : reading.capRuntime && reading.serviceCds.length
          ? `@sap/cds is in package.json and a service model (${reading.serviceCds.join(', ')}) is in the package, but neither the start script nor the entry starts CAP — not verified.`
          : reading.capRuntime
            ? '@sap/cds is in package.json, but no CDS service model is in the package.'
            : 'No @sap/cds dependency in package.json, so nothing starts a CAP runtime.',
    });
    caps.push({
      key: 'service-model',
      label: 'CDS service model',
      status: reading.serviceCds.length ? (capRunning ? 'implemented' : 'proposed') : 'missing',
      evidence: reading.serviceCds.length
        ? `${reading.serviceCds.join(', ')}${capRunning ? '' : reading.capRuntime ? ' — nothing in the package is shown to serve it' : ' — no runtime serves it'}.`
        : 'No .cds file in the package defines a service.',
    });
  }
  caps.push({
    key: 'http-service',
    label: 'HTTP service',
    status: reading.express.length || capRunning ? 'implemented' : reading.sources.length ? 'stub' : 'missing',
    evidence: reading.express.length
      ? `Express, in ${reading.express.join(', ')}.`
      : capRunning
        ? 'Served by the CAP runtime.'
        : 'No source file starts an HTTP server.',
  });
  caps.push({
    key: 'persistence',
    label: 'Persistence',
    status: reading.capRuntime && reading.schemaCds.length ? 'implemented' : reading.schemaCds.length ? 'proposed' : 'missing',
    evidence: reading.schemaCds.length
      ? `${reading.schemaCds.join(', ')}${reading.capRuntime ? '' : ' — a model only; no database is bound'}.`
      : 'No data model in the package.',
  });
  caps.push({
    key: 'sap-data',
    label: 'Connection to an SAP system',
    status: reading.sapClient.length ? 'implemented' : 'missing',
    evidence: reading.sapClient.length
      ? `An SAP client is used in ${reading.sapClient.join(', ')}; no connection to a system has been verified by Clean-Core.io.`
      : 'No source file uses an SAP client; the service works on data it holds itself.',
  });
  caps.push({
    key: 'authentication',
    label: 'Authentication and authorization',
    status: reading.authMiddleware.length ? 'implemented' : reading.authDeclared ? 'proposed' : 'missing',
    evidence: reading.authMiddleware.length
      ? `Wired in ${reading.authMiddleware.join(', ')}; not reviewed for business authorization (company code, customer).`
      : reading.authDeclared
        ? 'Libraries are declared in package.json, but no source file wires a strategy or middleware.'
        : 'Nothing in the package authenticates a caller.',
  });
  if (reading.publisher.length) {
    caps.push({
      key: 'erp-events',
      label: 'Events from the ERP',
      status: 'stub',
      evidence: `${reading.publisher.join(', ')}: publisher sketch — not bound to a BAdI or standard event, not compiled in SAP; no consumer in the package.`,
    });
  }
  caps.push({
    key: 'ui',
    label: 'User interface',
    status: reading.ui.length ? 'implemented' : 'missing',
    evidence: reading.ui.length ? reading.ui.join(', ') : 'No UI (Fiori, UI5 or HTML) in the package.',
  });
  caps.push({
    key: 'tests',
    label: 'Automated tests',
    status: reading.testFiles.length ? 'implemented' : 'missing',
    evidence: reading.testFiles.length
      ? `${reading.testFiles.join(', ')} (${reading.runner}). Run status: ${TEST_STATUS_WORDS[facts.tests.status].toLowerCase()}.`
      : 'No test suite in the package.',
  });
  caps.push({
    key: 'lockfile',
    label: 'Pinned dependency versions (package-lock.json)',
    status: reading.lockfile ? 'implemented' : 'missing',
    evidence: reading.lockfile ? 'package-lock.json is in the package.' : 'No lockfile ships; install resolves the ranges in package.json.',
  });
  return caps;
}

/** CAP is the proposed architecture: the target or the recommendation is CAP, or the package carries CDS files. */
function capArchitectureProposed(reading: PackageReading, facts: DeliveryFacts): boolean {
  return (
    facts.decision.targetCode === 'cap' ||
    (facts.decision.targetCode === null && facts.decision.recommendation?.code === 'cap') ||
    reading.schemaCds.length > 0 ||
    reading.serviceCds.length > 0
  );
}

/** What was built, in one sentence — the reviewer's "Mock-backed Express prototype; CAP architecture proposed, not implemented". */
export function implementationStatement(reading: PackageReading, facts: DeliveryFacts): string {
  if (reading.kind === 'abap') {
    return 'Delivered implementation: ABAP objects for an abapGit import — not imported into, activated in or run in an SAP system.';
  }
  if (reading.kind !== 'node') return 'Delivered implementation: none — the package holds documents only.';
  const capRunning = reading.capRuntime && reading.capServed && reading.serviceCds.length > 0;
  const what = capRunning ? 'CAP service' : reading.express.length ? 'Express service' : 'Node.js code';
  // CO review F10: no SAP client says where the data does not come from, not that it is synthetic.
  const data = reading.sapClient.length ? 'with an SAP client in the code (no connection verified)' : 'on data whose source is not recorded';
  const delivered = `delivered implementation: ${what} ${data}`;
  return capArchitectureProposed(reading, facts) && !capRunning
    ? `CAP architecture proposed; ${delivered}.`
    : `${delivered.charAt(0).toUpperCase()}${delivered.slice(1)}.`;
}

/**
 * Data mode — what is recorded about where the service's data comes from.
 *
 * It used to read "Synthetic/mock data only" whenever no source file called an
 * SAP system (CO review F10, 12.10.2026). That was an inference: the generated
 * engine takes whatever normalised data its caller hands in, and a real
 * offline extract is as possible as a demo set. No run records a data mode
 * today, so the package says it is not recorded instead of guessing. An SAP
 * client in the code is said as such — and never as "live", because nothing
 * verified a connection.
 */
export type DataMode = 'not-recorded' | 'sap-client-unverified' | 'not-applicable';

export function dataMode(reading: PackageReading): { mode: DataMode; sentence: string } {
  if (reading.kind !== 'node') {
    return { mode: 'not-applicable', sentence: 'Not applicable — the package runs inside an SAP system once imported; it has not been.' };
  }
  return reading.sapClient.length
    ? {
        mode: 'sap-client-unverified',
        sentence: `An SAP client is used in ${reading.sapClient.join(', ')}; no connection to a live system has been verified, and no run recorded where the data came from.`,
      }
    : {
        mode: 'not-recorded',
        sentence: 'Not recorded. No source file calls an SAP system, and no run recorded where the data came from: the code may build its own sample data or take what its caller hands in, and this package does not say which (PP review, 12.10.2026).',
      };
}

