/* ------------------------------------------------------------ the collector */

/**
 * The archive before it is an archive: the page adds files the way it added
 * them to JSZip (`file`, `folder(...).file`), and the finished list is written
 * into the ZIP in one go. A later file at the same path replaces an earlier one.
 */
export function createDeliveryBundle() {
  const entries: BundleEntry[] = [];
  const file = (path: string, content: string, origin?: FileOrigin) => {
    const at = entries.findIndex((e) => e.path === path);
    if (at !== -1) entries.splice(at, 1);
    entries.push(origin ? { path, content, origin } : { path, content });
  };
  return {
    entries,
    file,
    folder: (prefix: string) => ({
      file: (name: string, content: string, origin?: FileOrigin) => file(`${prefix}/${name}`, content, origin),
    }),
  };
}

/* ------------------------------------------------------- reading the files */

const CODE_EXT = /\.(ts|tsx|js|mjs|cjs)$/i;
const TEST_NAME = /(^|\/)(test\.(ts|js)|[^/]+\.(test|spec)\.(ts|js))$/i;
const NOT_RUNTIME_DIRS = new Set(['docs', 'erp-triggers', '.github', 'test', 'tests', '__tests__']);

const isTestPath = (p: string) => TEST_NAME.test(p);

export type TestRunner = 'node:test' | 'playwright';

/** The runner a suite is written for, read off its imports. `node:test` is the platform's runner (`lib/test-sandbox/core.ts`). */
export function suiteRunner(content: string): TestRunner {
  return /from\s+['"]@playwright\/test['"]|require\(\s*['"]@playwright\/test['"]\s*\)/.test(content) ? 'playwright' : 'node:test';
}

interface PackageJsonShape {
  name?: unknown;
  main?: unknown;
  scripts?: Record<string, unknown>;
  dependencies?: Record<string, unknown>;
  devDependencies?: Record<string, unknown>;
  [key: string]: unknown;
}

function parseJsonObject(text: string | undefined): PackageJsonShape | null {
  if (typeof text !== 'string') return null;
  try {
    const v = JSON.parse(text) as unknown;
    return v && typeof v === 'object' && !Array.isArray(v) ? (v as PackageJsonShape) : null;
  } catch {
    return null;
  }
}

const deps = (pkg: PackageJsonShape | null): Record<string, string> => {
  const out: Record<string, string> = {};
  for (const block of [pkg?.dependencies, pkg?.devDependencies]) {
    if (block && typeof block === 'object') for (const [k, v] of Object.entries(block)) if (typeof v === 'string') out[k] = v;
  }
  return out;
};

/** Code lines: neither blank nor a comment. */
function codeLines(content: string): number {
  return content
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('//') && !l.startsWith('*') && !l.startsWith('/*')).length;
}

/** What the package's own files say about it. Every field is a fact about the files, nothing else. */
export interface PackageReading {
  kind: 'node' | 'abap' | 'documents-only';
  packageJson: PackageJsonShape | null;
  dependencies: Record<string, string>;
  capRuntime: boolean;
  /**
   * Something in the package starts CAP: the start script runs `cds-serve` / `cds run|serve|watch`,
   * or the service entry imports @sap/cds and calls `cds.serve` / `cds.server`. A dependency and a
   * .cds file alone do not — the entry may start plain Express.
   */
  capServed: boolean;
  serviceCds: string[];
  schemaCds: string[];
  express: string[];
  sapClient: string[];
  authMiddleware: string[];
  authDeclared: boolean;
  publisher: string[];
  testFiles: string[];
  runner: TestRunner | null;
  lockfile: boolean;
  ui: string[];
  sources: string[];
}

export function readPackage(entries: readonly BundleEntry[], route: DeliveryFacts['route']): PackageReading {
  const paths = entries.map((e) => e.path);
  const byPath = new Map(entries.map((e) => [e.path, e.content]));
  const pkg = parseJsonObject(byPath.get('package.json'));
  const all = deps(pkg);
  const code = entries.filter((e) => CODE_EXT.test(e.path) && !e.path.startsWith('docs/'));
  const sources = code.filter((e) => !isTestPath(e.path)).map((e) => e.path);
  const cds = entries.filter((e) => /\.cds$/i.test(e.path));
  const imports = (re: RegExp) => code.filter((e) => !isTestPath(e.path) && re.test(e.content)).map((e) => e.path);
  const testFiles = code.filter((e) => isTestPath(e.path)).map((e) => e.path);
  const abap = paths.some((p) => /\.abap$/i.test(p) && !p.startsWith('erp-triggers/'));
  const kind: PackageReading['kind'] =
    route === 'abap-cloud' || (abap && !pkg && code.length === 0) ? 'abap' : code.length > 0 || pkg ? 'node' : 'documents-only';
  const start = typeof pkg?.scripts?.start === 'string' ? pkg.scripts.start : '';
  const entry = serviceEntry({ packageJson: pkg, sources });
  const entryContent = entry ? byPath.get(entry) ?? '' : '';
  const capServed =
    /(^|[\s;&|])(cds-serve|cds-ts\s+(run|serve|watch)|cds\s+(run|serve|watch))\b/.test(start) ||
    (/from\s+['"]@sap\/cds['"]|require\(\s*['"]@sap\/cds['"]\s*\)/.test(entryContent) && /\bcds\s*\.\s*(serve|server)\b/.test(entryContent));
  return {
    kind,
    packageJson: pkg,
    dependencies: all,
    capRuntime: '@sap/cds' in all,
    capServed,
    serviceCds: cds.filter((e) => /\bservice\s+[\w.]+/.test(e.content)).map((e) => e.path),
    schemaCds: cds.filter((e) => /\bentity\s+[\w.]+/.test(e.content) && !/\bservice\s+[\w.]+/.test(e.content)).map((e) => e.path),
    express: imports(/from\s+['"]express['"]|require\(\s*['"]express['"]\s*\)/),
    // An SAP client in the code: the Cloud SDK, or CAP connecting to a remote service.
    sapClient: imports(/['"]@sap-cloud-sdk\/[\w-]+['"]|cds\.connect\.to\s*\(/),
    // Authentication that is wired, not merely declared: a strategy or the middleware in use.
    authMiddleware: imports(/passport\.(authenticate|use)\s*\(|new\s+\w*Strategy\s*\(|createSecurityContext\s*\(|requires\s*:\s*['"]authenticated-user['"]/),
    authDeclared: ['passport', '@sap/xssec', 'passport-jwt'].some((d) => d in all),
    publisher: paths.filter((p) => p.startsWith('erp-triggers/') && /\.abap$/i.test(p)),
    testFiles,
    runner: (() => {
      const suite = code.find((e) => isTestPath(e.path));
      return suite ? suiteRunner(suite.content) : null;
    })(),
    lockfile: paths.includes('package-lock.json'),
    ui: paths.filter((p) => /^(app|webapp)\//.test(p) || /\.(html|view\.xml)$/i.test(p)),
    sources,
  };
}

