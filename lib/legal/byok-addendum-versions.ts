/**
 * The archive of the Additional Agreement on Own Model Keys — one entry per
 * published version, each in German and English.
 *
 * Clause 12 of the agreement: every version stays published with its date and
 * the SHA-256 digest of its wording at clean-core.io/terms/byok-addendum (and
 * /de), at least as long as a record of its acceptance is kept. The same rules
 * as `lib/terms-versions.ts`: an archived file never changes; a correction is a
 * new version (ZV-BYOK-1.1). The digest is taken over the LF-normalised file.
 *
 * No imports, so a client component can show the identifier and digests.
 */

export interface ArchivedAddendumFile {
  lang: 'en' | 'de';
  file: string;
  sha256: string;
}

export interface ArchivedAddendumVersion {
  /** The identifier a consent record names, e.g. "ZV-BYOK-1.0". */
  id: string;
  /** The provider the version covers. */
  provider: 'anthropic';
  /** Effective date as the text states it, per language. */
  effectiveOn: { en: string; de: string };
  files: readonly ArchivedAddendumFile[];
}

export const BYOK_ADDENDUM_ARCHIVE_DIR = 'docs/byok-addendum';

export const ARCHIVED_BYOK_ADDENDUM_VERSIONS: readonly ArchivedAddendumVersion[] = [
  {
    // Fassung 1.1 of the legal texts (3.0.21), effective on the release date
    // (open value `releaseDate`, 9 November 2026, confirmed by the owner on
    // 06.11.2026). The files were regenerated by `scripts/legal/archive-terms.ts`
    // with it, before publication.
    id: 'ZV-BYOK-1.0',
    provider: 'anthropic',
    effectiveOn: { en: '9 November 2026', de: '9. November 2026' },
    files: [
      {
        lang: 'en',
        file: 'docs/byok-addendum/ZV-BYOK-1.0.md',
        sha256: '0d56ecbbad6e61a86fe34af36548d2f3280421fc7b3ad22388272913cebbe8ec',
      },
      {
        lang: 'de',
        file: 'docs/byok-addendum/ZV-BYOK-1.0.de.md',
        sha256: '673acd8e8a1ca4fc06da11821b602ebc9fbce009570950104ee384eab465e25a',
      },
    ],
  },
];

export function archivedAddendum(id: string): ArchivedAddendumVersion | null {
  return ARCHIVED_BYOK_ADDENDUM_VERSIONS.find((v) => v.id === id) ?? null;
}

/** The digest of the wording a consent to `id` in `lang` refers to, or null. */
export function archivedAddendumSha256(id: string, lang: 'en' | 'de'): string | null {
  return archivedAddendum(id)?.files.find((f) => f.lang === lang)?.sha256 ?? null;
}
