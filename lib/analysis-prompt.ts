/**
 * What the engine read about the program's purpose, for the model — roadmap
 * 3.0.11 "In short" (owner, 12.10.2026): where the purpose needs words the
 * code does not hold, a model may phrase it from the engine's facts, and its
 * wording is held against them (`lib/program-summary-check.ts`). So the facts
 * go in as a block, and asIsContext must open from them.
 */
export function programFactsBlock(facts: ProgramSummaryFacts | null | undefined): string {
  if (!facts) return '';
  const summary = programSummary(facts);
  const lines = [
    'PROGRAM FACTS — what the deterministic engine read about this program. Ground truth for asIsContext and summary:',
    ...summary.lines.map((l) => `- [${l.key}] ${l.text}`),
    ...(facts.inputs.length
      ? [`- [selection screen] ${facts.inputs.map((i) => `${i.name}: ${i.label}${i.labelFrom === 'screen' ? '' : ' (no screen text)'}`).join('; ')}`]
      : []),
    ...facts.fixedLists.slice(0, 3).map((l) => `- [fixed list in the code, L${l.lineStart}-${l.lineEnd}] ${l.item}: ${l.columns.join(' | ')} = ${l.rows.map((r) => r.join(' | ')).join(' ; ')}`),
    ...(facts.screenTitles.length ? [`- [selection screen titles] ${facts.screenTitles.map((t) => t.text).join('; ')}`] : []),
    `- [level] ${summary.level.text}`,
  ];
  return lines.join('\n');
}

/**
 * The prompt of the Analyze stage, assembled in one place so it can be tested as a whole.
 *
 * It lived inline in the page, and the citation rule had two copies: the CITATIONS block from
 * narrative-anchors.ts, and a field comment that still said `[F-id]` after the engine's ids had been
 * `CC-…` all along. The parser rejected every citation the comment asked for, and the tests only
 * looked at the block (QA review of a0c108513165). The field comments now point at the block.
 */
export function buildAnalysisPrompt({
  targetDeployment,
  evidenceReport,
  routeReport,
  code,
  programFacts = null,
}: {
  targetDeployment: string | null | undefined;
  evidenceReport: AbapEvidenceReport;
  routeReport: ExtensibilityRouteReport;
  code: string;
  /** The engine's facts about what the program is for (`lib/program-summary-facts.ts`); absent: no block. */
  programFacts?: ProgramSummaryFacts | null;
}): string {
  return `You are analyzing a legacy SAP ABAP custom codebase for modernization. The customer has defined their target operating model as: SAP S/4HANA Cloud, ${targetDeployment === 'public' ? 'Public Edition (strict SaaS, zero modifications allowed)' : 'Private Edition / RISE (3-Tier Extensibility Model, allowing custom Tier 2 API wrappers)'}.
Name SAP's platform for side-by-side extensions "${BTP_FIRST}" at its first mention and "${BTP}" after that; keep the names of SAP services exactly as SAP names them.

Here is the deterministic Evidence Report generated by our static analysis parser. You MUST treat this as the absolute technical ground-truth and base your business/narrative assessment strictly on this data. Do NOT invent other database tables, legacy patterns, or findings that are not listed here:
${JSON.stringify(evidenceReport, null, 2)}
      
Analyze the legacy SAP ABAP code and the evidence findings to provide a highly practical, down-to-earth IT and Business assessment. You must return your output strictly in JSON format. Do not include any markdown formatting, HTML, or explanations outside the JSON object. The JSON must exactly match this TypeScript schema, and you MUST populate the fields 'cleanCoreScore' and 'extensibilityRouting' with the exact pre-calculated values provided below:

No field of this output states an amount of money — no cost, saving, price, budget or ROI in any currency. Nothing in this analysis rests on approved cost assumptions, and an amount you write is removed before anyone reads it.

${programFactsBlock(programFacts)}

${anchorInstruction(evidenceReport.findings, code.split(/\r?\n/).length)}

${SAP_REFERENCE_PROMPT_RULES}

${OPTION_COMPARISON_RULE} Write that comparison into recommendations.cloudReadiness.

interface AnalysisData {
  projectTitle: string;
  cleanCoreScore: number; // YOU MUST USE EXACTLY THIS VALUE: ${routeReport.cleanCoreScore}
  summary: string; // Plain english business executive summary. Every sentence that states something about THIS program must end with an anchor in one of the forms listed under CITATIONS above. General advice stays uncited.
  asIsContext: string; // Describe what the legacy program does. Same citation rule: anchor every claim about this code. Open with two plain sentences for a business reader, built only from PROGRAM FACTS: what the program is for, who uses it, which business objects, what it produces, and what it does not do. You may give the business meaning of a code value only as a reading of it (e.g. "FAC, read as facilities"). Never name a business object or table PROGRAM FACTS do not list; never say it posts, sends mail or runs an approval when PROGRAM FACTS say it does not; no money, savings or accuracy claims.
  standardFit: {
    potential: 'High' | 'Medium' | 'Low'; // 'High' only when the rationale lists, capability by capability, the standard function that covers each one. Otherwise 'Medium' or 'Low'.
    targetStandardProcess: string; // The standard process in words. An app ID, scope item or communication scenario only under the SAP IDENTIFIERS rules above.
    rationale: string; // The capabilities the code performs, which of them a named standard function covers, and which are unconfirmed or not known (target release, usage, volumes). No claim of full coverage without that list.
  };
  gaps: Array<{
    title: string; 
    severity: 'High' | 'Medium' | 'Low'; 
    strategy: string; 
    rationale: string; 
    complexity: 'High' | 'Medium' | 'Low'; 
  }>;
  recommendations: {
    keepCoreClean: string; // STEP 1: What standard SAP replacement exists? Name the EXACT standard object (e.g. "Use released CDS view I_Customer instead of SELECT on KNA1"). Mark each API as "(Catalog Match)", "(Candidate)", or "(Needs Validation)" based on whether you are certain the API exists and covers the use case, and follow the SAP IDENTIFIERS rules above. Do NOT say "rewrite" here — only name the standard alternative.
    decommissioning: string; // STEP 2: What legacy objects can be RETIRED after the standard alternative from Step 1 is adopted and validated? Never say "delete" — use "retire after replacement validation, data migration assessment, and business sign-off". Be explicit about which custom objects are candidates for retirement. Must be consistent with keepCoreClean.
    cloudReadiness: string; // STEP 3: First the option comparison required above: which option you recommend, the reason over the others, and what is not known that could change it. If Step 1 appears to replace the legacy code, name the capabilities that rests on and say the fit is to be confirmed before the code is retired — never claim it covers all functionality. If Step 1 only partially covers, describe ONLY the remaining gap that needs ABAP Cloud or Tier 2 wrapping. For complex programs, describe a HYBRID approach: which components go to RAP/In-App, which to CAP on ${BTP}, which to Integration Suite/Event Mesh, and which to Fiori/UI5. NEVER contradict Step 1 or Step 2.
  };
  strategicNextSteps: string[]; 
  extensibilityRouting: {
    // YOU MUST USE EXACTLY THESE PRE-CALCULATED VALUES:
    recommendedRoute: "${routeReport.recommendedRoute}";
    confidenceScore: ${routeReport.confidenceScore};
    rationale: "${routeReport.rationale.replace(/"/g, '\\"')}";
    targetArtifact: "${routeReport.targetArtifact}";
    decisionTreeCheckpoints: ${JSON.stringify(routeReport.checkpoints)};
    comparativeAnalysis: ${JSON.stringify(routeReport.comparativeAnalysis)};
  };
  businessValueAnalysis: {
    legacyAssetScore: number; 
    technicalDebtLevel: 'Low' | 'Medium' | 'High';
    valueDrivers: string[]; 
    plainEnglishActionPlan: string[]; // No money: no costs, savings, ROI or currency amounts anywhere in this object — nothing here rests on approved cost assumptions.
  };
}

Legacy Code to Analyze:
${code}`;
}
