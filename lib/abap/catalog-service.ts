const CR: CloudificationArtifact = crLatest as unknown as CloudificationArtifact;
const CR_CLASS: CloudificationArtifact = crClassifications as unknown as CloudificationArtifact;

export type CatalogConfidence = 'curated' | 'sap-official';

export interface MergedApiEntry extends SapApiEntry {
  confidence: CatalogConfidence;
  /** verbatim repo state when the entry (also) exists in the repo layer */
  releaseState?: string;
  /** all successors from the repo (curated layer only knows the primary) */
  successors?: { name: string; tadir: string }[];
  conceptNote?: string;
}

function tadirToType(tadir: string): SapApiObjectType {
  switch (tadir) {
    case 'DDLS':
    case 'VIEW': return 'CDS View';
    case 'SRVD':
    case 'SRVB': return 'OData API';
    case 'FUNC': return 'BAPI';
    default: return 'Unknown';
  }
}

/**
 * The no-path verdict of one release-file entry: no object successor, and a
 * concept note in its place or a state other than released. Shared by
 * `buildMerged` and the snapshot branch of `hasNoReleasedApiPath`, so the two
 * cannot drift apart.
 */
function releaseEntryHasNoPath(e: NormalizedEntry): boolean {
  if (e.successors?.[0]) return false;
  return Boolean(e.conceptNote) || e.state?.toLowerCase() !== 'released';
}

/** The no-path verdict of a classification-only entry: `noAPI`, no successor, no concept note. */
function classificationEntryHasNoPath(e: NormalizedEntry): boolean {
  return e.state?.toLowerCase() === 'noapi' && !e.successors?.length && !e.conceptNote;
}

function buildMerged(): { map: Record<string, MergedApiEntry>; noPath: Set<string> } {
  const map: Record<string, MergedApiEntry> = {};
  const noPath = new Set<string>();

  // Layer 2 first (so layer 1 overwrites).
  for (const [name, e] of Object.entries<NormalizedEntry>(CR.entries ?? {})) {
    const primary = e.successors?.[0];

    if (primary) {
      map[name] = {
        view: primary.name,
        type: tadirToType(primary.tadir),
        confidence: 'sap-official',
        releaseState: e.state,
        successors: e.successors,
        conceptNote: e.conceptNote,
      };
    } else if (releaseEntryHasNoPath(e)) {
      // Successor is a concept, not an object — do NOT fabricate a mapping. Or:
      // listed, not released, no successor → honest no-path signal.
      noPath.add(name);
    }
    // released && no successor → object itself is a released API; nothing to map.
  }

  // Layer 2b: the classification file, which this loop used to skip entirely.
  //
  // Finding 20fe6d7b4308 (QA full review of b88c77b, confirmed): `buildMerged`
  // read CR.entries only, so the 8,397 objects that exist ONLY in
  // cloudification-repo.classifications-sap.json never reached `noPath`. 367 of
  // them carry `state: noAPI` — SAP's statement that the object is not intended
  // for customer use — without a successor and without a concept note, and for
  // every one of them `hasNoReleasedApiPath()` answered `false`. Reachable
  // effect: `deriveFeasibility` (usage-join.ts) called such an object
  // `clean-core-ready` after an SCMON/UPL import, which is the engine claiming a
  // path it never looked for. Counted against the shipped artifacts, not
  // estimated (tests/catalog-no-path-classification.spec.ts re-counts them).
  //
  // Scope, deliberately narrow:
  //   noAPI, no successor  → no path. This is the finding.
  //   noAPI, with successor→ SAP names the replacement, so a path exists; the
  //                          object is still level D and the catalog page names
  //                          the successor (getObjectDimensions), but "no path"
  //                          would be untrue.
  //   classicAPI           → a documented classic API (level B). Not released
  //                          for ABAP Cloud, but calling 7,805 documented APIs
  //                          "no released path" is a different verdict than the
  //                          one this flag carries, and not one SAP's data
  //                          states.
  // Objects listed in BOTH files are left to the release loop above: the release
  // state decides before the classification state, exactly as in
  // `gradeFromSapStates`.
  for (const [name, e] of Object.entries<NormalizedEntry>(CR_CLASS.entries ?? {})) {
    if (CR.entries?.[name]) continue;
    if (classificationEntryHasNoPath(e)) noPath.add(name);
  }

  // Layer 1: curated entries always win (field-level knowledge).
  for (const [name, e] of Object.entries(SAP_API_CATALOG)) {
    const repo = CR.entries?.[name];
    map[name] = {
      ...e,
      confidence: 'curated',
      releaseState: repo?.state,
      successors: repo?.successors,
    };
    noPath.delete(name); // a curated mapping overrides a repo no-path verdict
  }

  return { map, noPath };
}

const built = buildMerged();

/** Drop-in for evidence-model's STANDARD_TABLE_MAP (superset of SapApiEntry). */
export const MERGED_TABLE_MAP: Record<string, MergedApiEntry> = built.map;

/** Objects with an honest 'no released-API path' verdict from the repo layer. */
export const NO_PATH_OBJECTS: ReadonlySet<string> = built.noPath;

export function resolveApi(objectName: string): MergedApiEntry | undefined {
  return MERGED_TABLE_MAP[(objectName || '').toUpperCase()];
}

/**
 * Whether the catalog shows no released-API path for an object.
 *
 * Omitted, or naming the default file, the answer is `NO_PATH_OBJECTS`. Naming
 * another shipped snapshot (a Private Edition release list, roadmap 7.10), the
 * release state comes from that snapshot under the rules `buildMerged`
 * applies: the curated layer still wins, the classification file is
 * release-agnostic. `/api/abcd-classify` used to answer this from the default
 * file while grading from the snapshot, so one response mixed two catalogs
 * under one snapshot reference (QA review of e7372791c70d).
 */
export function hasNoReleasedApiPath(objectName: string, snapshot?: string): boolean {
  const key = (objectName || '').toUpperCase();
  const release = releaseArtifact(snapshot);
  if (release === CR) return NO_PATH_OBJECTS.has(key);
  if (Object.prototype.hasOwnProperty.call(SAP_API_CATALOG, key)) return false;
  const entry = release.entries?.[key];
  if (entry) return releaseEntryHasNoPath(entry);
  const classification = CR_CLASS.entries?.[key];
  return Boolean(classification && classificationEntryHasNoPath(classification));
}

/** Who names a successor: SAP's release file, or Clean-Core.io's curated layer. */
export type SuccessorProvenance = 'sap' | 'curated';

export interface PrimarySuccessor {
  name: string;
  type: SapApiObjectType;
  source: SuccessorProvenance;
}

/**
 * The successor a public page leads with, and who names it.
 *
 * SAP's own successor wins when the release file names one. Otherwise a curated
 * mapping (`SAP_API_CATALOG`) may still name a target — KONV → I_PricingElement,
 * where SAP's file carries only a state. That target is Clean-Core.io's field
 * knowledge, not SAP's statement, and a page that printed it "per the SAP
 * Cloudification Repository" put our words in SAP's mouth (codex code-public-03).
 * The type follows the name it describes: a curated entry's type belongs to the
 * curated view, not to SAP's successor.
 */
export function primarySuccessor(objectName: string): PrimarySuccessor | undefined {
  const entry = resolveApi(objectName);
  const sap = entry?.successors?.[0];
  if (sap?.name) return { name: sap.name, type: tadirToType(sap.tadir), source: 'sap' };
  if (entry?.view) return { name: entry.view, type: entry.type, source: 'curated' };
  return undefined;
}

export const MERGED_CATALOG_SIZE =Object.keys(MERGED_TABLE_MAP).length;

/**
 * Lightweight stats for the public surfaces.
 *
 * `classifiedObjects` counts the UNION of both repository artifacts, because
 * that is the set of objects we can state a clean core level for. Counting only
 * the release file would understate coverage by the 8,410 objects the
 * classification file adds — and would contradict the A–D census on
 * /sap-clean-core-object-classification, which is the kind of mismatch that gets
 * a figure mis-cited.
 */
export function getCatalogStats(): {
  classifiedObjects: number;
  mappedWithSuccessor: number;
  syncDate: string;
} {
  const keys = new Set<string>([
    ...Object.keys(CR.entries ?? {}),
    ...Object.keys(CR_CLASS.entries ?? {}),
  ]);
  // Newest of the two syncs — the figure is only as current as its stalest half,
  // but the label reads "as of", so the later date is the honest one to show.
  const dates = [CR.meta?.fetchedAt, CR_CLASS.meta?.fetchedAt].filter(Boolean) as string[];
  const syncDate = dates.length ? dates.sort().slice(-1)[0].slice(0, 10) : '';

  return {
    classifiedObjects: keys.size,
    mappedWithSuccessor: MERGED_CATALOG_SIZE,
    syncDate,
  };
}

/**
 * Traceability string for Audit Pack / model card, e.g.
 * "2024.FPS02 + CR:latest@e3b0c442 (4812 entries, fetched 2026-07-01)"
 */
export function getMergedCatalogVersion(): string {
  const m = CR.meta;
  if (!m?.sourceSha256) return SAP_API_CATALOG_VERSION; // stub / pre-first-sync
  const shortSha = m.sourceSha256.slice(0, 8);
  const day = (m.fetchedAt || '').slice(0, 10);
  return `${SAP_API_CATALOG_VERSION} + CR:${m.release}@${shortSha} (${m.entryCount} entries, fetched ${day})`;
}


/* ---------- which snapshot answers (roadmap 7.10, CR-02) ---------- */

/**
 * The release files a lookup can read, by registry key.
 *
 * `latest` is always here — it is imported above and every page reads it.
 * The Private Edition files (`pce-latest` and the release-pinned ones) are
 * registered by `lib/abap/catalog-snapshots.ts`, which only server code
 * imports: this module also reaches the browser (through the evidence engine),
 * and ~6 MB of PCE data has no business in a browser bundle. A key that was
 * never registered is not shipped, and a lookup that names it is refused.
 */
const RELEASE_ARTIFACTS = new Map<string, CloudificationArtifact>([[CR.meta?.release || 'latest', CR]]);

/** Called by `lib/abap/catalog-snapshots.ts`; the key is the artifact's own `meta.release`. */
export function registerCatalogSnapshot(artifact: CloudificationArtifact): void {
  if (artifact?.meta?.release && artifact.meta.sourceSha256) RELEASE_ARTIFACTS.set(artifact.meta.release, artifact);
}

/** Whether a lookup can read this snapshot in this process. */
export function hasCatalogSnapshot(snapshot: string): boolean {
  return RELEASE_ARTIFACTS.has(snapshot);
}

function releaseArtifact(snapshot: string | undefined): CloudificationArtifact {
  if (snapshot === undefined) return CR;
  const artifact = RELEASE_ARTIFACTS.get(snapshot);
  if (!artifact) throw new CatalogSnapshotNotShipped(snapshot);
  return artifact;
}

/**
 * A catalog snapshot as the run records it: the registry key of the release
 * file and the digest of the raw file SAP served.
 *
 * The key alone is not an identity — `latest` is a moving name — so the digest
 * travels with it into the run's `AssessmentProfile`. This is what makes a
 * result say *which* catalog answered, and a resync visible as a different one.
 * Omitted, it is the default file (`latest`); named, the snapshot must be shipped.
 */
export function getCatalogSnapshotRef(snapshot?: string): { registryKey: string; sourceSha256: string } {
  const a = releaseArtifact(snapshot);
  return { registryKey: a.meta?.release || '', sourceSha256: a.meta?.sourceSha256 || '' };
}

/** A lookup asked for a snapshot this build does not ship. Never answered from another one. */
export class CatalogSnapshotNotShipped extends Error {
  readonly snapshot: string;
  constructor(snapshot: string) {
    super(
      `The catalog snapshot "${snapshot}" is not shipped with this build. No grade is given from another snapshot in its place.`,
    );
    this.name = 'CatalogSnapshotNotShipped';
    this.snapshot = snapshot;
  }
}

/**
 * The snapshot argument of the lookups below.
 *
 * Omitted, the lookup reads the one release file this build ships, as it
 * always has. Named, it must be that file: `pce-2023-3` asked for and `latest`
 * answered would be exactly the silent substitution 7.10 forbids ("ein
 * Latest-Eintrag ersetzt keinen älteren Release-Snapshot still").
 */
export function assertSnapshot(snapshot: string | undefined): void {
  releaseArtifact(snapshot);
}

/* ---------- clean core level (A–D) lookup ---------- */

/**
 * SAP's published state for an object, from both repository files.
 *
 * Server-side only: it reads the full generated artifacts (~5 MB combined), so
 * never import this into a client component. Client surfaces get the resolved
 * grade, not the map.
 */
export function getSapObjectStates(objectName: string, snapshot?: string): SapObjectStates {
  // The release state comes from the snapshot the profile reads; the
  // classification file (classicAPI / noAPI) is release-agnostic and shared.
  const releaseFile = releaseArtifact(snapshot);
  const key = (objectName || '').toUpperCase().trim();
  const release = releaseFile.entries?.[key];
  const classification = CR_CLASS.entries?.[key];

  // "isSapObject" drives the residual level C verdict, so it must mean "we know
  // this is SAP's". A Z/Y object is not, and a /NS/ object that appears in
  // neither artifact is unknown provenance — claiming either is SAP-internal
  // would be a grade we cannot support.
  const listed = Boolean(release || classification);
  return {
    releaseState: release?.state,
    classificationState: classification?.state,
    hasSuccessor: Boolean(release?.successors?.length || classification?.successors?.length),
    isSapObject: !isCustomerObject(key) && (listed || !isNamespacedObject(key)),
    isCustomerObject: isCustomerObject(key),
  };
}

/**
 * Clean core level for a single object, derived from SAP data where it exists.
 *
 * Returns provenance alongside the grade so the UI can separate a looked-up
 * grade from an estimated one — the distinction the public pages promise.
 *
 * This is the answer for the *name*. Where the code's use of the object is
 * known, `gradeSapObjectUse` is the answer the analysis shows.
 */
export function gradeSapObject(objectName: string, snapshot?: string): GradedObject {
  return gradeFromSapStates(getSapObjectStates(objectName, snapshot));
}

/**
 * Clean core level for one use of an object — the grade the analysis panel
 * shows next to a table the code reads or writes (`/api/abcd-classify`), and
 * the grade the reference corpus compares, so the two cannot drift apart.
 */
export function gradeSapObjectUse(objectName: string, use: ObjectUse | null, snapshot?: string): GradedObject {
  return gradeFromSapStatesForUse(getSapObjectStates(objectName, snapshot), use);
}

/* ---------- the two dimensions of a catalog object (roadmap 7.9, CR-01) ---------- */

/**
 * Where the replacement SAP names comes from.
 *
 * The release file and the classification file both carry successors, and they
 * do not carry the same ones: 225 of the 8,397 objects that exist only in the
 * classification file name a successor that `resolveApi()` cannot see, because
 * MERGED_TABLE_MAP is the release file's mapping layer and stays that. Naming
 * the file is how a reader can tell "SAP published a released successor" from
 * "SAP's classic classification points somewhere else".
 */
export type SuccessorSource = 'release' | 'classification';

/**
 * The two things a catalog object is, kept apart — roadmap 7.9, from CR-01.
 *
 * An object has a classic release status and an ABAP Cloud usability, and they
 * are not the same property. `CL_HTTP_UTILITY` is the case that makes it
 * obvious: the classification file calls it `classicAPI` (classic ABAP may use
 * it) while the release file calls it `notToBeReleased` and names
 * `CL_WEB_HTTP_UTILITY` as the successor. Collapsed into one letter, that object
 * looks like a misgrading — two independent reviews filed it as one (see the
 * comment on `gradeFromSapStates`).
 *
 * The LETTER is not a third thing and is not re-derived here: it stays the clean
 * core target reference (decision §9 no. 18), and `GradedObject.cloudView` /
 * `classicView` remain its two halves. What this adds is the successor — the
 * part of the answer that lives in whichever file happens to hold it — and the
 * honest marking of a verdict that is really a check.
 */
export interface ObjectDimensions {
  name: string;
  /** The clean core level and its two views. The target reference, unchanged. */
  graded: GradedObject;
  /** Verbatim state from objectReleaseInfo*.json, when the object is listed there. */
  releaseState?: string;
  /** Verbatim state from objectClassifications_SAP.json, when listed there. */
  classificationState?: string;
  /** The replacement SAP names, from whichever file names it. Empty when none. */
  successors: { name: string; tadir: string }[];
  successorSource: SuccessorSource | null;
  /** Successor named as a concept rather than an object ("Communication Targets"). */
  conceptNote?: string;
  /**
   * SAP marked the object for removal but named nothing to move to.
   *
   * Roadmap 7.9 is explicit that this is a CHECK and not an automatic D: 183 of
   * the 259 `deprecated` objects in the release file carry no successor, and for
   * those the grading rule's D is the strictest reading of a missing sentence,
   * not a replacement instruction anyone can act on. The letter is unchanged —
   * `abcd-classification.ts` derives it and is not touched here — but a surface
   * that prints it can now say which of the two it is looking at.
   */
  needsCheck: boolean;
  checkNote?: string;
}

/**
 * Both dimensions of one object, for the catalog page and anything else that
 * shows an object rather than a verdict.
 *
 * Server-side only, like the rest of this module: it reads the full artifacts.
 */
export function getObjectDimensions(objectName: string): ObjectDimensions {
  const key = (objectName || '').toUpperCase().trim();
  const release = CR.entries?.[key];
  const classification = CR_CLASS.entries?.[key];

  // Same precedence as the level: the release file decides, the classification
  // file answers where the release file is silent. The curated layer is not
  // consulted here — it is a transformation mapping, and `resolveApi()` remains
  // the place that speaks for it.
  let successors: { name: string; tadir: string }[] = [];
  let successorSource: SuccessorSource | null = null;
  if (release?.successors?.length) {
    successors = release.successors.map((s) => ({ name: s.name, tadir: s.tadir }));
    successorSource = 'release';
  } else if (classification?.successors?.length) {
    successors = classification.successors.map((s) => ({ name: s.name, tadir: s.tadir }));
    successorSource = 'classification';
  }

  const deprecated = release?.state?.toLowerCase() === 'deprecated';
  const needsCheck = deprecated && successors.length === 0 && !release?.conceptNote;

  return {
    name: key,
    graded: gradeSapObject(key),
    releaseState: release?.state,
    classificationState: classification?.state,
    successors,
    successorSource,
    conceptNote: release?.conceptNote ?? classification?.conceptNote,
    needsCheck,
    ...(needsCheck
      ? {
          checkNote:
            'SAP marks this object for removal but names no replacement. That is a check to run against the current release notes, not a finished verdict — the level reads the missing successor in the strictest way it can.',
        }
      : {}),
  };
}

/** SAP object types the repository files list that code reads and writes as data. */
const DATA_OBJECT_TYPES = new Set(['TABL', 'VIEW', 'DDLS']);

/**
 * Both answers for a data object whose level depends on the access, or `null`.
 *
 * The catalog page has no code to look at, so for KNA1 it cannot know whether
 * the reader reads or writes. Where that decides the level it shows both rather
 * than the stricter one alone; everywhere else there is one answer and this
 * returns nothing.
 *
 * Since codex code-engine-05 every SAP object written directly is D, so the
 * write answer alone no longer tells the page anything about *this* object:
 * it is the general row on `/method/levels`. Printed here it would sit on
 * thousands of released objects that cannot be written at all — a CDS view
 * (ABAP SQL cannot write one) or a structure, which the release file lists as
 * TABL just like a table. So the page shows two answers only where *reading*
 * moves the level away from the name — the notToBeReleased read — exactly the
 * objects it showed them for before; the analysis, which sees the statement,
 * is where the direct write is graded.
 */
export function gradeSapObjectUses(objectName: string): { read: GradedObject; write: GradedObject } | null {
  const key = (objectName || '').toUpperCase().trim();
  const tadir = CR.entries?.[key]?.tadir ?? CR_CLASS.entries?.[key]?.tadir;
  if (!tadir || !DATA_OBJECT_TYPES.has(tadir)) return null;
  const read = gradeSapObjectUse(key, 'read');
  const write = gradeSapObjectUse(key, 'write');
  if (read.grade === gradeSapObject(key).grade) return null;
  return read.grade === write.grade ? null : { read, write };
}

export interface LevelDerivationCensus {
  totalObjects: number;
  releaseFileOnly: number;
  classificationFileOnly: number;
  inBoth: number;
  /** Every state pairing that occurs, with the level it produces. */
  combinations: {
    releaseState: string | null;
    classificationState: string | null;
    grade: CloudReadinessGrade;
    objects: number;
    /**
     * How many of them SAP names a replacement for.
     *
     * Counted rather than inferred. The rule page needs it to say "21 of the 22
     * carry a successor", and writing that as `total - 1` would be arithmetic
     * standing in for a measurement — true today, and silently wrong the first
     * time a catalog sync changes the shape.
     */
    withSuccessor: number;
  }[];
}

/**
 * The derivation, counted rather than described.
 *
 * `/method/levels` publishes the precedence rule, and a rule page whose numbers
 * are typed by hand is a rule page that goes stale silently. Every figure it
 * prints comes from here, computed over the two artifacts at build time — so a
 * catalog sync that changes the shape of the data changes the page with it.
 *
 * The pairings matter more than the totals: the twenty-two objects where the two
 * files disagree are the whole reason the page exists, and they are a row here
 * rather than a sentence someone has to keep true.
 */
export function getLevelDerivationCensus(): LevelDerivationCensus {
  const releaseKeys = Object.keys(CR.entries ?? {});
  const classificationKeys = Object.keys(CR_CLASS.entries ?? {});
  const all = new Set<string>([...releaseKeys, ...classificationKeys]);

  let inBoth = 0;
  const buckets = new Map<string, LevelDerivationCensus['combinations'][number]>();

  for (const key of all) {
    const release = CR.entries?.[key];
    const classification = CR_CLASS.entries?.[key];
    if (release && classification) inBoth += 1;

    const releaseState = release?.state ?? null;
    const classificationState = classification?.state ?? null;
    const grade = gradeSapObject(key).grade;
    const hasSuccessor = Boolean(release?.successors?.length || classification?.successors?.length);

    // A deprecated object grades C or D depending on whether SAP named a
    // successor, so the successor flag is part of the pairing's identity.
    const id = `${releaseState}|${classificationState}|${grade}`;
    const existing = buckets.get(id);
    if (existing) {
      existing.objects += 1;
      if (hasSuccessor) existing.withSuccessor += 1;
    } else {
      buckets.set(id, {
        releaseState,
        classificationState,
        grade,
        objects: 1,
        withSuccessor: hasSuccessor ? 1 : 0,
      });
    }
  }

  return {
    totalObjects: all.size,
    // From the intersection, not from the total: `all.size - otherFile.length`
    // gives the same answer only while every object is in at least one file,
    // which is true today and is not a property either artifact guarantees.
    releaseFileOnly: releaseKeys.length - inBoth,
    classificationFileOnly: classificationKeys.length - inBoth,
    inBoth,
    combinations: [...buckets.values()].sort((a, b) => b.objects - a.objects),
  };
}

/** One of the two synced SAP artifacts the level is derived from. */
export interface LevelRuleArtifact {
  /** file name as SAP publishes it, taken from the URL that was fetched */
  file: string;
  /** the question this file answers — the reason there are two of them */
  question: string;
  /** registry key of the sync (e.g. 'latest', 'classifications-sap') */
  release: string;
  /** first eight hex characters of the SHA-256 of the raw file SAP served */
  sha256: string;
  /** date of the sync, YYYY-MM-DD */
  fetchedAt: string;
  entries: number;
}

export interface LevelRuleVersion {
  /** twelve hex characters over the rule's full decision table */
  fingerprint: string;
  /** how many distinct inputs that table covers — the fingerprint's reach */
  decisions: number;
  artifacts: LevelRuleArtifact[];
  /** the one line a reader can quote back at us */
  version: string;
}

let levelRuleVersionCache: LevelRuleVersion | null = null;

/**
 * Which version of the A–D rule produced the level you are looking at.
 *
 * Two halves, both measured:
 *
 *   the rule   — every input `gradeFromSapStatesForUse` can tell apart (the two
 *                states, the owner, and how the code uses the object),
 *                enumerated and hashed (see `level-rule-version.ts`). The states SAP actually
 *                ships are read out of the artifacts and folded into the domain,
 *                so a state nobody anticipated moves the fingerprint too.
 *   the data   — the release and the SHA-256 SAP served, per file, with the date
 *                of the sync.
 *
 * Nothing here is typed by hand, which is the whole point: `/method/levels`
 * prints this string, and a version string a page author maintains is correct
 * exactly once.
 */
export function getLevelRuleVersion(): LevelRuleVersion {
  if (levelRuleVersionCache) return levelRuleVersionCache;

  const statesOf = (a: CloudificationArtifact) =>
    [...new Set(Object.values(a.entries ?? {}).map((e) => e.state).filter(Boolean))];

  const decisions = enumerateLevelRule({
    releaseStates: statesOf(CR),
    classificationStates: statesOf(CR_CLASS),
  });
  const fingerprint = fingerprintLevelRule(decisions);

  const artifact = (a: CloudificationArtifact, question: string): LevelRuleArtifact => ({
    file: (a.meta?.source || '').split('/').pop() || 'unknown',
    question,
    release: a.meta?.release || 'unknown',
    sha256: (a.meta?.sourceSha256 || '').slice(0, 8),
    fetchedAt: (a.meta?.fetchedAt || '').slice(0, 10),
    entries: a.meta?.entryCount ?? Object.keys(a.entries ?? {}).length,
  });

  const artifacts = [
    artifact(CR, 'Can ABAP Cloud use this object?'),
    artifact(CR_CLASS, 'What does classic ABAP using it count as?'),
  ];

  levelRuleVersionCache = {
    fingerprint,
    decisions: decisions.length,
    artifacts,
    version: `levels ${fingerprint} · ${artifacts.map((a) => `${a.release}@${a.sha256}`).join(' · ')}`,
  };
  return levelRuleVersionCache;
}

/**
 * A–D distribution across everything SAP has published, for the public
 * reference page. This is a census of SAP's own data, not of any customer's
 * code — labelled as such wherever it is shown.
 */
export function getPublishedGradeDistribution(): {
  distribution: Record<CloudReadinessGrade, number>;
  totalObjects: number;
  releaseSource: { release: string; sha256: string; fetchedAt: string };
  classificationSource: { release: string; sha256: string; fetchedAt: string };
} {
  const distribution: Record<CloudReadinessGrade, number> = { A: 0, B: 0, C: 0, D: 0, Unknown: 0 };
  const seen = new Set<string>();

  const tally = (key: string) => {
    if (seen.has(key)) return;
    seen.add(key);
    distribution[gradeSapObject(key).grade] += 1;
  };

  for (const key of Object.keys(CR.entries ?? {})) tally(key);
  for (const key of Object.keys(CR_CLASS.entries ?? {})) tally(key);

  const src = (a: CloudificationArtifact) => ({
    release: a.meta?.release || 'unknown',
    sha256: (a.meta?.sourceSha256 || '').slice(0, 8),
    fetchedAt: (a.meta?.fetchedAt || '').slice(0, 10),
  });

  return {
    distribution,
    totalObjects: seen.size,
    releaseSource: src(CR),
    classificationSource: src(CR_CLASS),
  };
}
