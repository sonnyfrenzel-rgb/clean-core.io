#!/usr/bin/env node
/**
 * Writes `lib/test-sandbox/probe-runtime.ts` from
 * `scripts/acceptance/lib/probes.mjs` — the failure-pattern probes as a
 * string the app sends to the isolated test runner beside a generation
 * candidate (`lib/test-sandbox/probe-suite.ts`, roadmap 3.0.12). One source:
 * the acceptance harness owns the probes; run
 * `node scripts/transformation/sync-probe-runtime.mjs` after it changes them.
 * `tests/transformation-verify.spec.ts` fails when the two differ.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const source = fs.readFileSync(path.join(root, 'scripts', 'acceptance', 'lib', 'probes.mjs'), 'utf8').replace(/\r\n/g, '\n');
const out = `// GENERATED by scripts/transformation/sync-probe-runtime.mjs from scripts/acceptance/lib/probes.mjs — do not edit by hand.

/**
 * The failure-pattern probes (roadmap 3.0.12), as the text the app sends to
 * the isolated test runner as \`__cc_probe/probes.mjs\` beside a generation
 * candidate. Hash-bound like every file of a run (\`hashRunInputs\`). Read the
 * readable source in scripts/acceptance/lib/probes.mjs.
 */
export const PROBE_RUNTIME_JS: string = ${JSON.stringify(source)};
`;
fs.writeFileSync(path.join(root, 'lib', 'test-sandbox', 'probe-runtime.ts'), out);
process.stdout.write('lib/test-sandbox/probe-runtime.ts written\n');
