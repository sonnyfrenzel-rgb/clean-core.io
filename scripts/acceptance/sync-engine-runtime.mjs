#!/usr/bin/env node
/**
 * Writes `lib/test-sandbox/engine-runtime.ts` from
 * `scripts/acceptance/child/engine-cases-core.mjs` — the engine-case runtime as
 * a string the app sends to the isolated test runner beside the generated code.
 * One source: edit the .mjs, then run `node scripts/acceptance/sync-engine-runtime.mjs`.
 * `tests/engine-call-contract.spec.ts` fails when the two differ.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const source = fs.readFileSync(path.join(root, 'scripts', 'acceptance', 'child', 'engine-cases-core.mjs'), 'utf8').replace(/\r\n/g, '\n');
const out = `// GENERATED by scripts/acceptance/sync-engine-runtime.mjs from scripts/acceptance/child/engine-cases-core.mjs — do not edit by hand.

/**
 * The engine-case runtime (roadmap 3.0.12, owner 12.10.2026), as the text the
 * app sends to the isolated test runner as \`__cc_engine/runtime.mjs\` beside the
 * generated code. Hash-bound like every file of a run (\`hashRunInputs\`). Read
 * the readable source in scripts/acceptance/child/engine-cases-core.mjs.
 */
export const ENGINE_RUNTIME_JS: string = ${JSON.stringify(source)};
`;
fs.writeFileSync(path.join(root, 'lib', 'test-sandbox', 'engine-runtime.ts'), out);
process.stdout.write('lib/test-sandbox/engine-runtime.ts written\n');
